def download_methylation_data():
    """
    Download pre-computed methylation data from gannet server.
    
    Data was generated by 10-mCG-call.Rmd using modkit pileup.
    We use the .cov10.bedGraph files which are:
    - Pre-filtered for coverage >= 10
    - Smaller file sizes for faster processing
    
    Source: https://gannet.fish.washington.edu/v1_web/owlshell/bu-github/project-lake-trout/analyses/10-mCG-call/
    """
    print("\n" + "="*60)
    print("Step 1: Downloading CpG methylation data from gannet server")
    print("="*60)
    
    # Ensure methylation data directory exists
    ensure_directory(METH_DATA_DIR)
    
    downloaded = 0
    skipped = 0
    
    for sample in SAMPLES:
        # Use the coverage-filtered bedGraph files (much smaller)
        bedgraph_file = METH_DATA_DIR / f"{sample}.cov10.bedGraph"
        
        if file_exists_and_nonempty(bedgraph_file):
            print(f"  {sample}: Data already exists, skipping download...")
            skipped += 1
            continue
        
        # Download the bedGraph file
        url = f"{GANNET_URL}/{sample}.cov10.bedGraph"
        print(f"  Downloading {sample}.cov10.bedGraph...")
        
        cmd = f"wget -q -O {bedgraph_file} {url}"
        try:
            run_command(cmd, f"Downloading {sample}")
            if file_exists_and_nonempty(bedgraph_file):
                downloaded += 1
                print(f"    Downloaded successfully.")
            else:
                print(f"    WARNING: Download failed or empty file for {sample}")
        except Exception as e:
            print(f"    ERROR downloading {sample}: {e}")
    
    print(f"\n  Downloaded: {downloaded} files")
    print(f"  Already present: {skipped} files")
    print(f"  Total available: {downloaded + skipped} / {len(SAMPLES)} samples")
    
    return downloaded + skipped

