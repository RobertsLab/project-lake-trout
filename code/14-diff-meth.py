# Step 2: Parse and Merge Methylation Data
# =============================================================================

def parse_bedgraph(filepath, sample_name):
    """
    Parse bedGraph file with percent methylation.
    
    bedGraph format (4 columns):
    chrom, start, end, pct_methylation
    
    These files are already filtered for coverage >= 10 (cov10.bedGraph)
    
    Returns DataFrame with columns: chrom, pos, pct_meth
    """
    data = []
    
    if not file_exists_and_nonempty(filepath):
        print(f"  WARNING: File not found or empty: {filepath}")
        return pd.DataFrame()
    
    with open(filepath, 'r') as f:
        for line in f:
            if line.startswith('#') or line.startswith('track'):
                continue
            parts = line.strip().split('\t')
            if len(parts) < 4:
                continue
            
            try:
                chrom = parts[0]
                pos = int(parts[1])
                pct_modified = float(parts[3])
                
                data.append({
                    'chrom': chrom,
                    'pos': pos,
                    'pct_meth': pct_modified
                })
            except (ValueError, IndexError):
                continue
    
    df = pd.DataFrame(data)
    if not df.empty:
        df['sample'] = sample_name
    
    return df

def merge_methylation_data():
    """Merge methylation data from all samples into a unified matrix."""
    print("\n" + "="*60)
    print("Step 2: Merging methylation data across samples")
    print("="*60)
    
    all_data = []
    
    for sample in SAMPLES:
        # Use the coverage-filtered bedGraph files
        filepath = METH_DATA_DIR / f"{sample}.cov10.bedGraph"
        print(f"  Parsing {sample}...")
        df = parse_bedgraph(filepath, sample)
        if not df.empty:
            all_data.append(df)
            print(f"    Found {len(df):,} CpGs (pre-filtered for coverage >= {MIN_COVERAGE})")
    
    if not all_data:
        print("  ERROR: No methylation data found!")
        print("  Make sure to run the download step first or check the data directory.")
        return None
    
    # Combine all data
    combined = pd.concat(all_data, ignore_index=True)
    
    # Create methylation matrix: rows = CpG positions, columns = samples
    print("\n  Creating methylation matrix...")
    
    # Create position identifier
    combined['site_id'] = combined['chrom'] + ':' + combined['pos'].astype(str)
    
    # Pivot to wide format
    meth_matrix = combined.pivot_table(
        index='site_id',
        columns='sample',
        values='pct_meth',
        aggfunc='first'
    )
    
    # Parse site_id back to chrom and pos
    site_info = pd.DataFrame({
        'site_id': meth_matrix.index,
        'chrom': [s.split(':')[0] for s in meth_matrix.index],
        'pos': [int(s.split(':')[1]) for s in meth_matrix.index]
    }).set_index('site_id')
    
    print(f"  Total unique CpG sites: {len(meth_matrix):,}")
    print(f"  Samples in matrix: {list(meth_matrix.columns)}")
    
    # Save merged data
    output_file = OUTPUT_DIR / "methylation_matrix.csv"
    meth_matrix.to_csv(output_file)
    print(f"  Saved methylation matrix to: {output_file}")
    
    return meth_matrix, site_info

