def identify_dmrs(dm_results):
    """
    Identify Differentially Methylated Regions (DMRs) by merging 
    nearby significant DMCs.
    """
    print("\n" + "="*60)
    print("Step 4: Identifying Differentially Methylated Regions (DMRs)")
    print("="*60)
    
    # Filter for significant DMCs
    sig_df = dm_results[dm_results['significant']].copy()
    
    if len(sig_df) == 0:
        print("  No significant DMCs found. Cannot identify DMRs.")
        return None
    
    # Sort by chromosome and position
    sig_df = sig_df.sort_values(['chrom', 'pos'])
    
    dmrs = []
    current_dmr = None
    
    print(f"  Merging {len(sig_df)} significant DMCs into regions...")
    
    for _, row in sig_df.iterrows():
        chrom = row['chrom']
        pos = row['pos']
        direction = row['direction']
        
        if current_dmr is None:
            # Start new DMR
            current_dmr = {
                'chrom': chrom,
                'start': pos,
                'end': pos + 1,
                'direction': direction,
                'cpgs': [row],
                'n_cpgs': 1
            }
        elif (chrom == current_dmr['chrom'] and 
              pos - current_dmr['end'] <= DMR_MERGE_DISTANCE and
              direction == current_dmr['direction']):
            # Extend current DMR
            current_dmr['end'] = pos + 1
            current_dmr['cpgs'].append(row)
            current_dmr['n_cpgs'] += 1
        else:
            # Save current DMR and start new one
            if current_dmr['n_cpgs'] >= MIN_CPGS_PER_DMR:
                dmrs.append(current_dmr)
            current_dmr = {
                'chrom': chrom,
                'start': pos,
                'end': pos + 1,
                'direction': direction,
                'cpgs': [row],
                'n_cpgs': 1
            }
    
    # Don't forget last DMR
    if current_dmr is not None and current_dmr['n_cpgs'] >= MIN_CPGS_PER_DMR:
        dmrs.append(current_dmr)
    
    if not dmrs:
        print(f"  No DMRs with >= {MIN_CPGS_PER_DMR} CpGs found.")
        return None
    
    # Create DMR summary DataFrame
    dmr_data = []
    for i, dmr in enumerate(dmrs):
        cpg_df = pd.DataFrame(dmr['cpgs'])
        dmr_data.append({
            'dmr_id': f"DMR_{i+1}",
            'chrom': dmr['chrom'],
            'start': dmr['start'],
            'end': dmr['end'],
            'length': dmr['end'] - dmr['start'],
            'n_cpgs': dmr['n_cpgs'],
            'direction': dmr['direction'],
            'mean_diff': cpg_df['meth_diff'].mean(),
            'mean_pvalue': cpg_df['pvalue'].mean(),
            'min_pvalue': cpg_df['pvalue'].min(),
            'lean_mean': cpg_df['lean_mean'].mean(),
            'siscowet_mean': cpg_df['siscowet_mean'].mean()
        })
    
    dmr_df = pd.DataFrame(dmr_data)
    
    print(f"\n  DMR Summary:")
    print(f"    Total DMRs identified: {len(dmr_df)}")
    print(f"    Hypermethylated in Siscowet: {(dmr_df['direction'] == 'hyper_siscowet').sum()}")
    print(f"    Hypomethylated in Siscowet: {(dmr_df['direction'] == 'hypo_siscowet').sum()}")
    print(f"    Mean CpGs per DMR: {dmr_df['n_cpgs'].mean():.1f}")
    print(f"    Mean DMR length: {dmr_df['length'].mean():.1f} bp")
    
    # Save DMRs
    output_file = OUTPUT_DIR / "dmrs.csv"
    dmr_df.to_csv(output_file, index=False)
    print(f"\n  Saved DMRs to: {output_file}")
    
    # Save as BED file
    bed_file = OUTPUT_DIR / "dmrs.bed"
    with open(bed_file, 'w') as f:
        f.write("#chrom\tstart\tend\tname\tscore\tstrand\tmeth_diff\tn_cpgs\tdirection\n")
        for _, row in dmr_df.iterrows():
            score = int(min(abs(row['mean_diff']), 100))  # Score 0-100
            strand = "+" if row['direction'] == 'hyper_siscowet' else "-"
            f.write(f"{row['chrom']}\t{row['start']}\t{row['end']}\t")
            f.write(f"{row['dmr_id']}\t{score}\t{strand}\t")
            f.write(f"{row['mean_diff']:.2f}\t{row['n_cpgs']}\t{row['direction']}\n")
    print(f"  Saved DMRs BED file to: {bed_file}")
    
    # Create separate BED files for hyper and hypo
    hyper_df = dmr_df[dmr_df['direction'] == 'hyper_siscowet']
    hypo_df = dmr_df[dmr_df['direction'] == 'hypo_siscowet']
    
    if len(hyper_df) > 0:
        hyper_bed = OUTPUT_DIR / "dmrs_hyper_siscowet.bed"
        hyper_df[['chrom', 'start', 'end', 'dmr_id', 'n_cpgs', 'mean_diff']].to_csv(
            hyper_bed, sep='\t', index=False, header=False)
        print(f"  Saved hypermethylated DMRs to: {hyper_bed}")
    
    if len(hypo_df) > 0:
        hypo_bed = OUTPUT_DIR / "dmrs_hypo_siscowet.bed"
        hypo_df[['chrom', 'start', 'end', 'dmr_id', 'n_cpgs', 'mean_diff']].to_csv(
            hypo_bed, sep='\t', index=False, header=False)
        print(f"  Saved hypomethylated DMRs to: {hypo_bed}")
    
    return dmr_df

