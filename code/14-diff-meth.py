"""
14-diff-meth.py - Differential Methylation Analysis

This script identifies differentially methylated regions (DMRs) between 
Siscowet and Lean lake trout (Salvelinus namaycush) subspecies using 
PacBio HiFi methylation data.

Analysis Pipeline:
1. Download pre-computed CpG methylation data from gannet server
   (generated by 10-mCG-call.Rmd using modkit pileup)
2. Merge methylation data across all samples
3. Perform statistical testing for differential methylation
4. Identify differentially methylated CpGs (DMCs)
5. Define differentially methylated regions (DMRs)
6. Annotate DMRs with gene information

Sample Groups:
- LEAN: bc2041, bc2069, bc2070, bc2068
- SISCOWET: bc2071, bc2073, bc2072, bc2096

Data Source:
https://gannet.fish.washington.edu/v1_web/owlshell/bu-github/project-lake-trout/analyses/10-mCG-call/

Author: Generated for project-lake-trout
Date: 2025-12-07
"""

