# =============================================================================

def differential_methylation_analysis(meth_matrix, site_info):
    """
    Perform differential methylation analysis between Lean and Siscowet.
    
    Uses Mann-Whitney U test for each CpG site.
    """
    print("\n" + "="*60)
    print("Step 3: Differential methylation analysis")
    print("="*60)
    
    lean_samples = [s for s in SAMPLES_LEAN if s in meth_matrix.columns]
    siscowet_samples = [s for s in SAMPLES_SISCOWET if s in meth_matrix.columns]
    
    print(f"  LEAN samples: {lean_samples}")
    print(f"  SISCOWET samples: {siscowet_samples}")
    
    if len(lean_samples) < MIN_SAMPLES or len(siscowet_samples) < MIN_SAMPLES:
        print(f"  ERROR: Need at least {MIN_SAMPLES} samples per group!")
        return None
    
    results = []
    
    print(f"\n  Testing {len(meth_matrix)} CpG sites...")
    
    for idx, site_id in enumerate(meth_matrix.index):
        if idx % 100000 == 0 and idx > 0:
            print(f"    Processed {idx:,} sites...")
        
        # Get methylation values for each group
        lean_vals = meth_matrix.loc[site_id, lean_samples].dropna()
        sisc_vals = meth_matrix.loc[site_id, siscowet_samples].dropna()
        
        # Skip if not enough samples have data
        if len(lean_vals) < MIN_SAMPLES or len(sisc_vals) < MIN_SAMPLES:
            continue
        
        # Calculate means
        lean_mean = lean_vals.mean()
        sisc_mean = sisc_vals.mean()
        diff = sisc_mean - lean_mean  # Positive = higher in Siscowet
        
        # Statistical test (Mann-Whitney U)
        try:
            stat, pval = stats.mannwhitneyu(lean_vals, sisc_vals, alternative='two-sided')
        except Exception:
            continue
        
        chrom = site_info.loc[site_id, 'chrom']
        pos = site_info.loc[site_id, 'pos']
        
        results.append({
            'site_id': site_id,
            'chrom': chrom,
            'pos': pos,
            'lean_mean': lean_mean,
            'siscowet_mean': sisc_mean,
            'meth_diff': diff,
            'n_lean': len(lean_vals),
            'n_siscowet': len(sisc_vals),
            'statistic': stat,
            'pvalue': pval
        })
    
    if not results:
        print("  ERROR: No valid comparisons!")
        return None
    
    df = pd.DataFrame(results)
    
    # Multiple testing correction (Benjamini-Hochberg)
    print(f"\n  Applying FDR correction to {len(df)} tests...")
    reject, qvals, _, _ = multipletests(df['pvalue'], method='fdr_bh')
    df['qvalue'] = qvals
    
    # Classify significance
    df['significant'] = (
        (df['pvalue'] < P_VALUE_THRESHOLD) & 
        (np.abs(df['meth_diff']) >= DIFF_THRESHOLD * 100)  # Convert to percentage scale
    )
    df['significant_fdr'] = (
        (df['qvalue'] < Q_VALUE_THRESHOLD) & 
        (np.abs(df['meth_diff']) >= DIFF_THRESHOLD * 100)
    )
    
    # Direction of change
    df['direction'] = np.where(df['meth_diff'] > 0, 'hyper_siscowet', 'hypo_siscowet')
    
    print(f"\n  Results summary:")
    print(f"    Total CpG sites tested: {len(df)}")
    print(f"    Significant (p < {P_VALUE_THRESHOLD}, diff >= {DIFF_THRESHOLD*100}%): {df['significant'].sum()}")
    print(f"    Significant after FDR (q < {Q_VALUE_THRESHOLD}): {df['significant_fdr'].sum()}")
    
    sig_df = df[df['significant']]
    if len(sig_df) > 0:
        print(f"    - Hypermethylated in Siscowet: {(sig_df['direction'] == 'hyper_siscowet').sum()}")
        print(f"    - Hypomethylated in Siscowet: {(sig_df['direction'] == 'hypo_siscowet').sum()}")
    
    # Save results
    output_file = OUTPUT_DIR / "differential_methylation_cpgs.csv"
    df.to_csv(output_file, index=False)
    print(f"\n  Saved all CpG results to: {output_file}")
    
    # Save significant CpGs
    sig_file = OUTPUT_DIR / "significant_dmcs.csv"
    df[df['significant']].to_csv(sig_file, index=False)
    print(f"  Saved significant DMCs to: {sig_file}")
    
    return df

