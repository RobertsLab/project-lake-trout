def annotate_dmrs_with_genes(dmr_df):
    """Intersect DMRs with gene annotations."""
    print("\n" + "="*60)
    print("Step 5: Annotating DMRs with gene information")
    print("="*60)
    
    if dmr_df is None or len(dmr_df) == 0:
        print("  No DMRs to annotate.")
        return None
    
    if not GENES_BED.exists():
        print(f"  WARNING: Gene annotation file not found: {GENES_BED}")
        return dmr_df
    
    # Create temporary DMR BED for bedtools
    temp_dmr_bed = OUTPUT_DIR / "temp_dmrs_for_intersect.bed"
    dmr_df[['chrom', 'start', 'end', 'dmr_id']].to_csv(
        temp_dmr_bed, sep='\t', index=False, header=False)
    
    # Run bedtools intersect
    output_file = OUTPUT_DIR / "dmrs_genes_intersect.bed"
    cmd = f"bedtools intersect -a {temp_dmr_bed} -b {GENES_BED} -wa -wb > {output_file}"
    
    try:
        run_command(cmd, "bedtools intersect DMRs with genes")
        
        if file_exists_and_nonempty(output_file):
            # Parse intersection results
            intersect_df = pd.read_csv(output_file, sep='\t', header=None)
            
            # Columns: dmr_chrom, dmr_start, dmr_end, dmr_id, gene_chrom, gene_start, gene_end, gene_name, ...
            if len(intersect_df.columns) >= 8:
                intersect_df.columns = ['dmr_chrom', 'dmr_start', 'dmr_end', 'dmr_id',
                                       'gene_chrom', 'gene_start', 'gene_end', 'gene_name'] + \
                                      [f'extra_{i}' for i in range(len(intersect_df.columns) - 8)]
                
                # Get unique genes per DMR
                dmr_genes = intersect_df.groupby('dmr_id')['gene_name'].apply(
                    lambda x: ';'.join(x.unique())
                ).reset_index()
                dmr_genes.columns = ['dmr_id', 'overlapping_genes']
                
                # Merge back to DMR table
                dmr_df = dmr_df.merge(dmr_genes, on='dmr_id', how='left')
                dmr_df['overlapping_genes'] = dmr_df['overlapping_genes'].fillna('')
                
                n_with_genes = (dmr_df['overlapping_genes'] != '').sum()
                print(f"\n  DMRs overlapping genes: {n_with_genes} / {len(dmr_df)}")
                
                # Save annotated DMRs
                output_file = OUTPUT_DIR / "dmrs_annotated.csv"
                dmr_df.to_csv(output_file, index=False)
                print(f"  Saved annotated DMRs to: {output_file}")
        else:
            print("  No gene overlaps found.")
    
    except Exception as e:
        print(f"  WARNING: Could not annotate with genes: {e}")
    
    # Clean up temp file
    if temp_dmr_bed.exists():
        temp_dmr_bed.unlink()
    
    return dmr_df

