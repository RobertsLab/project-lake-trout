def main():
    """Main function to run the complete differential methylation analysis."""
    print("="*60)
    print("Differential Methylation Analysis")
    print("Siscowet vs Lean Lake Trout")
    print("="*60)
    print(f"\nLEAN samples: {', '.join(SAMPLES_LEAN)}")
    print(f"SISCOWET samples: {', '.join(SAMPLES_SISCOWET)}")
    print(f"Methylation data: {METH_DATA_DIR}")
    print(f"Output directory: {OUTPUT_DIR}")
    
    # Ensure output directory exists
    ensure_directory(OUTPUT_DIR)
    
    # Step 1: Download methylation data from gannet server
    n_available = download_methylation_data()
    if n_available < len(SAMPLES):
        print(f"\nWARNING: Only {n_available}/{len(SAMPLES)} samples available.")
    
    # Step 2: Merge methylation data
    result = merge_methylation_data()
    if result is None:
        print("\nERROR: Could not merge methylation data. Exiting.")
        return
    
    meth_matrix, site_info = result
    
    # Step 3: Differential methylation analysis
    dm_results = differential_methylation_analysis(meth_matrix, site_info)
    
    if dm_results is None:
        print("\nERROR: Differential methylation analysis failed. Exiting.")
        return
    
    # Step 4: Identify DMRs
    dmr_df = identify_dmrs(dm_results)
    
    # Step 5: Annotate DMRs with genes
    if dmr_df is not None:
        dmr_df = annotate_dmrs_with_genes(dmr_df)
    
    # Step 6: Generate summary report
    generate_summary_report(dm_results, dmr_df)
    
    # Step 7: Create visualization data
    create_visualization_data(dm_results, dmr_df)
    
    print("\n" + "="*60)
    print("Differential Methylation Analysis Complete!")
    print("="*60)
    print(f"\nOutput files are in: {OUTPUT_DIR}")
    print("\nKey output files:")
    print("  - methylation_matrix.csv          : Per-sample methylation values")
    print("  - differential_methylation_cpgs.csv : All tested CpGs with statistics")
    print("  - significant_dmcs.csv            : Significant DMCs only")
    print("  - significant_dmcs.bed            : Significant DMCs in BED format")
    print("  - dmrs.csv                        : Differentially methylated regions")
    print("  - dmrs.bed                        : DMRs in BED format")
    print("  - dmrs_annotated.csv              : DMRs with gene annotations")
    print("  - methylation_diff_*.bedGraph     : For genome browser visualization")
    print("  - differential_methylation_report.txt : Summary report")

if __name__ == "__main__":
    main()

