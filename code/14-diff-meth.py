def create_visualization_data(dm_results, dmr_df):
    """Create data files for visualization (e.g., IGV tracks)."""
    print("\n" + "="*60)
    print("Step 7: Creating visualization data")
    print("="*60)
    
    if dm_results is None:
        return
    
    # Create bedGraph of methylation differences for genome browser
    bedgraph_file = OUTPUT_DIR / "methylation_diff_siscowet_vs_lean.bedGraph"
    
    with open(bedgraph_file, 'w') as f:
        f.write(f'track type=bedGraph name="Meth_Diff_Sisc-Lean" description="Methylation difference (Siscowet - Lean)" visibility=full color=0,0,255 altColor=255,0,0 autoScale=on\n')
        for _, row in dm_results.iterrows():
            f.write(f"{row['chrom']}\t{row['pos']}\t{row['pos']+1}\t{row['meth_diff']:.2f}\n")
    
    print(f"  Created bedGraph: {bedgraph_file}")
    
    # Create significant DMCs BED file
    sig_bed = OUTPUT_DIR / "significant_dmcs.bed"
    sig_df = dm_results[dm_results['significant']]
    
    with open(sig_bed, 'w') as f:
        f.write("#chrom\tstart\tend\tname\tscore\tstrand\n")
        for _, row in sig_df.iterrows():
            score = int(min(abs(row['meth_diff']), 100))
            strand = "+" if row['meth_diff'] > 0 else "-"
            name = f"DMC_{row['chrom']}_{row['pos']}"
            f.write(f"{row['chrom']}\t{row['pos']}\t{row['pos']+1}\t{name}\t{score}\t{strand}\n")
    
    print(f"  Created significant DMCs BED: {sig_bed}")

